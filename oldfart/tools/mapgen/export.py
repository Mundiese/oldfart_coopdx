ROW_BEGIN = "    -- BEGIN GENERATED VENUES (tools/mapgen export - edit with the tool, not by hand)"
ROW_END = "    -- END GENERATED VENUES"
class ExportError(ValueError):
    pass
def _fresh(filename, name):
    spec = importlib.util.spec_from_file_location(name, os.path.join(v1.TOOLS, filename))
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module
def generated_dir(mod):
    return os.path.join(mod, "tools", "venues-generated")
def _quiet(fn, *args):
    buf = io.StringIO()
    with contextlib.redirect_stdout(buf):
        code = fn(*args)
    return code, buf.getvalue()
def run_tools(mod, check=False):
    mod = os.path.abspath(mod)
    m = _fresh("make-arenas.py", "mapgen_export_arenas")
    m.ACTORS = os.path.join(mod, "actors")
    m.LUA = os.path.join(mod, "of_venues.lua")
    m.PICTURES = os.path.join(mod, "docs", "arenas")
    m.GENERATED = generated_dir(mod)
    out = []
    code, text = _quiet(m.main, ["--check"] if check else [])
    out.append(("make-arenas", code, text))
    lv = _fresh("make-venue-levels.py", "mapgen_export_levels")
    lv.MOD = mod
    lv.HERE = os.path.join(mod, "tools")
    lv.LEVELS = os.path.join(mod, "levels")
    code, text = _quiet(lv.main, ["--check"] if check else [])
    out.append(("make-venue-levels", code, text))
    return out
def _lua_str(s):
    return '"%s"' % str(s).replace("\\", "\\\\").replace('"', '\\"')
def default_modes(arena):
    from . import modeready
    return modeready.usable(arena, FAMILY_MODES.get(arena.get("family", "shooter"), []))
def arena_row(arena, comment=True):
    modes = arena.get("onlyFor") or default_modes(arena)
    every_but = isinstance(arena.get("notFor"), list)
    if every_but:
        kept_off = list(arena["notFor"])
    else:
        kept_off = [k for k in arena.get("notFor") or [] if k not in modes]
    g = arena.get("generator", {})
    lines = ([
        "    -- %s: generated by tools/mapgen (seed %s, candidate %s)."
        % (arena["name"], g.get("seed"), g.get("candidate")),
    ] if comment else []) + [
        "    {",
        "        key = %s, name = %s," % (_lua_str(arena["key"]), _lua_str(arena["name"])),
        "        blurb = %s," % _lua_str(arena["blurb"]),
        "        note = %s," % _lua_str(arena["note"]),
        "        script = %s, base = %s, area = 1, act = 1,"
        % (_lua_str(arena["script"]), _lua_str(arena["level"])),
    ] + ([
        "        ground = %s," % _lua_str(arena["ground"]),
    ] if arena.get("ground") and arena["level"] == "empty" else []) + [
        "        sweep = SWEEP_BARE,",
        "        venue = true,",
        "        suits = { %s }," % ", ".join(_lua_str(x) for x in modes),
    ] + ([
        "        family = %s," % _lua_str(arena.get("family") or "shooter"),
    ] if every_but else [
        "        onlyFor = { %s }," % ", ".join(_lua_str(x) for x in modes),
    ]) + ([
        "        notFor = { %s }," % ", ".join(_lua_str(x) for x in kept_off),
    ] if kept_off or every_but else []) + ([
        "        face = { top = %s, bottom = %s },"
        % (_lua_str(arena["face"]["top"]), _lua_str(arena["face"]["bottom"])),
    ] if _face(arena) else []) + [
        "    },",
    ]
    return "\n".join(lines)
def _after_sky_keep(text):
    at = text.find('key = "skykeep"')
    if at < 0:
        raise ExportError("of_arena.lua: no venue rows to put the generated ones after")
    end = text.find("\n    },\n", at)
    if end < 0:
        raise ExportError("of_arena.lua: the Sky Keep's row has no end")
    return end + len("\n    },\n")
_GENERATED_ROW = re.compile(r'(?:[ \t]*\n)*    \{\n        key = "([a-z][a-z0-9]*)",[^\n]*\n')
def generated_span(text):
    a, b = text.find(ROW_BEGIN), text.find(ROW_END)
    if a >= 0 and b > a:
        return a, b + len(ROW_END)
    a = b = _after_sky_keep(text)
    while True:
        m = _GENERATED_ROW.match(text, b)
        if m is None:
            break
        end = text.find("\n    },\n", m.start(1))
        if end < 0:
            break
        row = text[m.start():end]
        if ('script = "of_%s"' % m.group(1)) not in row or "venue = true," not in row:
            break
        b = end + len("\n    },\n")
    return a, b
def _face(arena):
    f = arena.get("face")
    return isinstance(f, dict) and isinstance(f.get("top"), str) \
        and isinstance(f.get("bottom"), str)
def painting_paths(mod, key):
    from . import painting
    return [os.path.join(mod, "textures", painting.tex_name(key, half) + ".tex")
            for half in ("top", "bottom")]
def painting_files(layout, mod, key, name):
    try:
        from . import modpack, painting
        files, face = painting.export_files(modpack.prepared_arena(layout, key, name), key)
    except Exception:
        return None
    if not face:
        return None
    for rel, data in files.items():
        path = os.path.join(mod, *rel.split("/"))
        os.makedirs(os.path.dirname(path), exist_ok=True)
        with open(path, "wb") as handle:
            handle.write(data)
    return face
def splice_rows(text, rows, bare=False):
    if bare:
        a, b = generated_span(text)
        if text.startswith(ROW_BEGIN, a) and text.startswith("\n", b):
            b += 1
        return text[:a] + "".join(r + "\n" for r in rows) + text[b:]
    block = "\n".join([ROW_BEGIN] + rows + [ROW_END])
    a, b = text.find(ROW_BEGIN), text.find(ROW_END)
    if a >= 0 and b > a:
        return text[:a] + block + text[b + len(ROW_END):]
    end = _after_sky_keep(text)
    return text[:end] + block + "\n" + text[end:]
def _luaregion():
    import sys
    if "of_luaregion" not in sys.modules:
        spec = importlib.util.spec_from_file_location(
            "of_luaregion", os.path.join(v1.TOOLS, "luaregion.py"))
        module = importlib.util.module_from_spec(spec)
        spec.loader.exec_module(module)
        sys.modules["of_luaregion"] = module
    return sys.modules["of_luaregion"]
def _existing_keys(mod):
    with open(os.path.join(mod, "of_arena.lua"), encoding="utf-8") as handle:
        text = handle.read()
    try:
        a, b = generated_span(text)
        text = text[:a] + text[b:]
    except ExportError:
        pass
    return set(re.findall(r'\bkey = "([^"]+)"', text))
def explain_export(layout, key, name):
    objs = layout.get("objects") or []
    lines = ["export %s (%s):" % (name, key),
             "  tools/venues-generated/%s.json   the layout (make-arenas reads it)" % key,
             "  of_venues.lua LAYOUTS            the table: %d pieces, %d spawns%s%s"
             % (len(layout["pieces"]), len(layout["spawns"]),
                ", %d Forge objects (synced, free play only unless a mode is named)"
                % len(objs) if objs else "",
                ", the venue's light" if (layout.get("look") or {}).get("light") else ""),
             "  levels/of_%s/ + level_of_%s_entry.lvl   its own level (make-venue-levels)"
             % (key, key),
             "  of_arena.lua                     the arena row, onlyFor %s (each named mode offers it)"
             % ", ".join(layout.get("onlyFor") or default_modes(layout))]
    return "\n".join(lines)
LUA_PER_PIECE = 110
LUA_PER_OBJECT = 160
LUA_PER_MOVER = 200
LUA_FIXED = 6144
LEVEL_BYTES = 8192
ACTOR_FALLBACK = 4096
_arenas_tool = None
