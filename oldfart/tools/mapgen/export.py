def estimate_growth(layout, mod):
    global _arenas_tool
    layout = layout or {}
    pieces = layout.get("pieces") or []
    lua = (LUA_FIXED + LUA_PER_PIECE * len(pieces)
           + LUA_PER_OBJECT * len(layout.get("objects") or [])
           + LUA_PER_MOVER * len(layout.get("movers") or []))
    actors = os.path.join(mod, "actors")
    have = [n for n in (os.listdir(actors) if os.path.isdir(actors) else [])
            if n.startswith("of_ak_") and n.endswith("_geo.bin")]
    each = (sum(os.path.getsize(os.path.join(actors, n)) for n in have) // len(have)
            if have else ACTOR_FALLBACK)
    each = max(each, 1024)
    new = set()
    try:
        if _arenas_tool is None:
            _arenas_tool = _fresh("make-arenas.py", "mapgen_export_estimate")
        m = _arenas_tool
        for p in pieces:
            if p.get("tex") == m.INVISIBLE or m.runtime_token(p) is not None:
                continue
            name = m.model_name(p)
            if not os.path.exists(os.path.join(actors, name + ".bin")):
                new.add(name)
    except Exception:
        new = {(p.get("kind"), p.get("tex"), p.get("w"), p.get("h"), p.get("d"))
               for p in pieces}
    pictures = each * len(new)
    level, exact = level_bytes(layout, mod)
    return {"lua": lua, "actors": pictures, "pictures": len(new), "level": level,
            "level_exact": exact, "total": lua + pictures + level}
def level_bytes(layout, mod):
    if not (layout or {}).get("pieces") or (layout or {}).get("bake") is False:
        return LEVEL_BYTES, False
    try:
        import sys
        if v1.TOOLS not in sys.path:
            sys.path.insert(0, v1.TOOLS)
        import venuebake
        levels = os.path.join(mod, "levels")
        if not os.path.isfile(os.path.join(levels, "level_%s_entry.lvl"
                                           % (layout.get("level") or "empty2"))):
            levels = None
        got = venuebake.measure(layout, levels=levels, shade=True).get("lvl_bytes")
    except Exception:
        got = None
    if not got:
        return LEVEL_BYTES, False
    return int(got), True
def level_words(n):
    seconds = n / 1048576.0 * 1.5
    wait = "under a second" if seconds < 1 else "about %.0f seconds" % seconds
    return "about %d KB, %s more for each player who joins" % (round(n / 1024.0), wait)
def wall_after(layout, mod):
    rs = _release_size()
    now = rs.engine_bytes(mod)
    return now, now + estimate_growth(layout, mod)["total"], rs.MAX_MOD_SIZE
def wall_refusal(now, after, wall):
    if after < wall:
        return None
    rs = _release_size()
    return ("the mod folder is %s; this map would take it to about %.1f MB - past Coop "
            "DX's 35 MB wall, where the mod is greyed out in the mod list. Make room "
            "first: remove an exported venue (Export > Remove a venue), music it does not "
            "use, or install a release copy of the mod (tools/make-release.sh: no tests, "
            "tools or comments)" % (rs.wall_line(now), after / 1048576.0))
def export_mod(layout, mod, key, name, blurb=None, note=None):
    mod = os.path.abspath(mod)
    for need in ("of_venues.lua", "of_arena.lua", os.path.join("levels", layout["level"])):
        if not os.path.exists(os.path.join(mod, need)):
            raise ExportError("%s has no %s - is it the mod folder?" % (mod, need))
    if not KEY_RE.match(key or ""):
        raise ExportError("key %r: 3-24 lower-case letters/digits, starting with a letter" % key)
    if key in v1.venue_keys() or key in _existing_keys(mod):
        raise ExportError("key %r is already a place in of_arena.lua - pick a new one" % key)
    too_big = wall_refusal(*wall_after(layout, mod))
    if too_big:
        raise ExportError(too_big)
    arena = json.loads(json.dumps(layout))
    arena["key"] = key
    arena["name"] = name
    arena["script"] = "of_" + key
    fam = arena.get("family", "shooter")
    params = arena.get("generator", {}).get("params", {})
    across = 2 * (params.get("I", 0) + params.get("G", 0) + params.get("B", 0))
    arena["blurb"] = blurb or layout.get("blurb") or "a generated %s keep for sixteen players" % fam
    arena["note"] = note or layout.get("note") or ("a generated island keep, %d across: %s centre, %s lanes, "
                             "four walled bastions" % (across, params.get("centre", "?"),
                                                        params.get("lane", "?")))
    for p in arena["pieces"]:
        p.pop("model", None)
    if isinstance(arena.get("look"), dict):
        arena["look"] = bake.fold_hour(bake.export_look(arena["look"]))
    from .families.race import race_world
    start = race_world(arena)
    if start is not None:
        arena["world"] = start
    elif not arena.get("world"):
        from .worldspawn import ensure
        ensure(arena)
    face = painting_files(layout, mod, key, name)
    if face:
        arena["face"] = face
    else:
        arena.pop("face", None)
    folder = generated_dir(mod)
    os.makedirs(folder, exist_ok=True)
    path = os.path.join(folder, key + ".json")
    with open(path, "w", encoding="utf-8") as handle:
        json.dump(arena, handle, indent=1, sort_keys=True)
        handle.write("\n")
    res = _finish(mod, [path] + ([p for p in painting_paths(mod, key)] if face else []))
    res["painting"] = face
    return res
def unexport_mod(mod, key):
    mod = os.path.abspath(mod)
    path = os.path.join(generated_dir(mod), key + ".json")
    if not os.path.exists(path):
        raise ExportError("no generated venue %r in %s" % (key, mod))
    os.remove(path)
    for rel in ("levels/level_of_%s_entry.lvl" % key, "docs/arenas/%s.png" % key):
        if os.path.exists(os.path.join(mod, rel)):
            os.remove(os.path.join(mod, rel))
    for tex in painting_paths(mod, key):
        if os.path.exists(tex):
            os.remove(tex)
    import shutil
    shutil.rmtree(os.path.join(mod, "levels", "of_" + key), ignore_errors=True)
    return _finish(mod, [path])
def _finish(mod, touched):
    folder = generated_dir(mod)
    bare = _luaregion().is_release(mod)
    rows = []
    if os.path.isdir(folder):
        for name in sorted(os.listdir(folder)):
            if name.endswith(".json"):
                with open(os.path.join(folder, name), encoding="utf-8") as handle:
                    rows.append(arena_row(json.load(handle), comment=not bare))
    lua = os.path.join(mod, "of_arena.lua")
    with open(lua, encoding="utf-8") as handle:
        text = handle.read()
    if bare:
        new = _luaregion().finish(splice_rows(text, rows, bare=True), mod)
    else:
        new = splice_rows(text, rows) if rows or ROW_BEGIN in text else text
    if new != text:
        with open(lua, "w", encoding="utf-8") as handle:
            handle.write(new)
    report = run_tools(mod)
    bad = [(t, c, o) for t, c, o in report if c != 0]
    if bad:
        raise ExportError("; ".join("%s: %s" % (t, o.strip()) for t, c, o in bad))
    return {"touched": touched + [lua], "tools": report}
def draw(arena, path):
    m = v1.arenas_module()
    rects = [m.footprint(p) for p in arena["pieces"]]
    cx = (min(r[0] for r in rects) + max(r[1] for r in rects)) / 2.0
    cz = (min(r[2] for r in rects) + max(r[3] for r in rects)) / 2.0
    def moved(t):
        t = dict(t)
        t["x"] -= cx
        t["z"] -= cz
        return t
    a = dict(arena)
    a.setdefault("key", "generated")
    a["pieces"] = [moved(p) for p in arena["pieces"]]
    a["spawns"] = [moved(s) for s in arena["spawns"]]
    a["marks"] = [dict(moved(s), label="") for s in arena.get("survey", {}).get("points", [])
                  [len(arena["spawns"]):]]
    if abs(cx) > 1 or abs(cz) > 1:
        a["marks"].append({"x": -cx, "z": -cz, "label": "origin (world spawn)"})
    m.draw(a, kit.colours(), path)
def write_out(result, out, report_text=None, wish=None, not_understood=None, card=True):
    os.makedirs(out, exist_ok=True)
    files = []
    def put(name, text):
        p = os.path.join(out, name)
        with open(p, "w", encoding="utf-8") as handle:
            handle.write(text)
        files.append(p)
    layout = result.layout()
    put("brief.json", result.brief.to_json())
    put("layout.json", json.dumps(layout, indent=1, sort_keys=True) + "\n")
    put("candidates.json", json.dumps([c.summary() for c in result.candidates], indent=1)
        + "\n")
    if report_text:
        put("report.md", report_text)
    png = os.path.join(out, "top.png")
    draw(result.best.arena, png)
    files.append(png)
    if card:
        try:
            from .report import report as card_report
        except Exception as why:
            files.append("(no report card: %s)" % why.__class__.__name__)
        else:
            arena = dict(layout)
            name = result.brief["name"] or ""
            arena["key"] = (result.brief["key"]
                            or "".join(ch for ch in name.lower() if ch.isalnum()) or "map")
            rep = arena.get("report", {})
            cands = [{"name": "candidate %d" % c.index, "quality": c.quality,
                      "differs": candidate_words(c)}
                     for c in result.candidates if c.ok]
            _, jp, mp = card_report(
                arena, out, wish=wish, brief=result.brief.to_dict(),
                defaulted=list(result.brief.defaulted), done=rep.get("done"),
                not_understood=list(not_understood or []) + rep.get("not_understood", []),
                not_possible=rep.get("not_possible"), candidates=cands)
            files += [jp, mp]
    return files
def candidate_words(c):
    s = c.summary()
    words = [str(s.get("shape") or "-")]
    for k in ("centre", "lane"):
        if s.get(k) not in (None, "-"):
            words.append("%s %s" % (k, s[k]))
    return ", ".join(words)
